(function () {
  'use strict';

  // 1. Mobile Navigation Toggle
  try {
    const btn = document.getElementById('mobileMenuBtn');
    const panel = document.getElementById('mobileMenuPanel');
    const iconOpen = document.getElementById('menuIconOpen');
    const iconClose = document.getElementById('menuIconClose');

    if (btn && panel) {
      const setOpen = function (open) {
        panel.classList.toggle('hidden', !open);
        if (iconOpen) iconOpen.classList.toggle('hidden', open);
        if (iconClose) iconClose.classList.toggle('hidden', !open);
        btn.setAttribute('aria-expanded', String(open));
      };

      btn.addEventListener('click', function () {
        setOpen(panel.classList.contains('hidden'));
      });

      document.querySelectorAll('.mobile-link').forEach(function (el) {
        el.addEventListener('click', function () { setOpen(false); });
      });
    }
  } catch (err) {
    console.error('Mobile nav init error:', err);
  }

  // 2. Interactive Feature Showcase (Home Page)
  try {
    const featureTabs = document.querySelectorAll('.feature-tab');
    const featureTitle = document.getElementById('featureTitle');
    const featurePreviewImg = document.getElementById('featurePreviewImg');
    const featureLightboxBtn = document.getElementById('featureLightboxBtn');
    const featureBullets = document.getElementById('featureBullets');
    const assemblySubToggle = document.getElementById('assemblySubToggle');
    const assemblySubtabs = document.querySelectorAll('.assembly-subtab');

    if (featureTabs.length && featureTitle && featurePreviewImg && featureBullets) {
      const FEATURE_DATA = {
        verbatim: {
          title: 'True Verbatim Transcription',
          src: '/assets/img/transcript-canvas.webp',
          alt: 'True Verbatim Transcription canvas in BadWords v4',
          caption: 'True Verbatim Transcription - Word-level transcript canvas',
          bullets: [
            'Faster-Whisper tuned to catch every stutter, "um", and false start instead of smoothing speech.',
            'Marks completely unintelligible audio as (...) so you can inspect it manually.',
            'Live chunked streaming with word-level timestamps across ~100 languages for frame-accurate cuts.'
          ]
        },
        script: {
          title: 'Smart Script Comparison',
          src: '/assets/img/script-sbs.webp',
          alt: 'Smart Script Comparison side-by-side view in BadWords v4',
          caption: 'Smart Script Comparison - Side-by-side DNA-inspired diff',
          bullets: [
            'DNA-inspired alignment highlights only deviations, mistakes, and retakes so you skip clean 1:1 matches.',
            'Automatically extracts technical terms and names from your script to boost AI transcription accuracy.',
            'Imports .txt, .docx, and .pdf scripts directly, with a side-by-side script comparison view.'
          ]
        },
        silence: {
          title: 'Instant Silence Detection & Fast Silence',
          src: '/assets/img/feature-silence-waveform.webp',
          alt: 'BadWords v4 Silence Detection panel and interactive waveform timeline',
          caption: 'Silence Detection & Waveform - Live RAM tuning at <5 ms',
          bullets: [
            'Auto-normalized audio makes the -42 dB silence threshold work out of the box across microphones.',
            'Island absorption swallows random short noises like desk bumps or coughs inside pauses automatically.',
            'Live sliders recalculate in <5 ms in RAM, and Fast Silence cuts an entire timeline in seconds without transcription.'
          ]
        },
        editor: {
          title: 'Standalone Mode & Multi-NLE Export',
          src: '/assets/img/feature-welcome-standalone.webp',
          alt: 'BadWords v4 Standalone File Drop Zone for local media',
          caption: 'Standalone Mode - Drag & drop video or audio without DaVinci Resolve',
          bullets: [
            'Drop video or audio files directly from disk with automatic background 360p proxy playback.',
            'Marquee box, Notepad-style text selection, or brush marking with real-time cut skipping playback.',
            'Export clean cut timelines to FCP7 XML (.xml), Apple FCPXML, OpenTimelineIO (.otio), or CMX 3600 EDL.'
          ]
        },
        assembly: {
          title: 'Assembly Panel & Timeline Heatmap',
          views: {
            panel: {
              src: '/assets/img/feature-assembly.webp',
              alt: 'BadWords v4 Assembly Options panel with color cut rules',
              caption: 'Assembly Panel - Per-color cut or marker rules'
            },
            heatmap: {
              src: '/assets/img/heatmap-preview.webp',
              alt: 'DaVinci Resolve Timeline Heatmap generated by BadWords',
              caption: 'Resolve Timeline Heatmap - Linked clips with color markers'
            }
          },
          bullets: [
            'Decide per color whether to auto-cut or leave as colored clip markers on a brand-new non-destructive timeline.',
            'Frame-accurate cuts on 23.976 / 29.97 / 59.94 fps, with optional Studio .drt pipeline to preserve Color, Fusion, and Fairlight.',
            'Project saves (.bws) include autosave and crash recovery, plus FCPXML fallback on Resolve Free 21.1+.'
          ]
        }
      };

      let currentAssemblyView = 'panel';

      const setMedia = function (src, alt, caption) {
        featurePreviewImg.src = src;
        featurePreviewImg.alt = alt;
        if (featureLightboxBtn) {
          featureLightboxBtn.setAttribute('data-lightbox-src', src);
          featureLightboxBtn.setAttribute('data-lightbox-caption', caption);
        }
      };

      const renderFeature = function (key) {
        const data = FEATURE_DATA[key];
        if (!data) return;

        featureTitle.textContent = data.title;
        if (key === 'assembly' && data.views) {
          if (assemblySubToggle) assemblySubToggle.classList.remove('hidden');
          const v = data.views[currentAssemblyView] || data.views.panel;
          setMedia(v.src, v.alt, v.caption);
        } else {
          if (assemblySubToggle) assemblySubToggle.classList.add('hidden');
          setMedia(data.src, data.alt, data.caption);
        }

        featureBullets.innerHTML = '';
        data.bullets.forEach(function (text) {
          const li = document.createElement('li');
          const dot = document.createElement('span');
          dot.className = 'bullet-dot';
          const span = document.createElement('span');
          span.textContent = text;
          li.appendChild(dot);
          li.appendChild(span);
          featureBullets.appendChild(li);
        });

        featureTabs.forEach(function (btn) {
          const active = btn.getAttribute('data-feature-tab') === key;
          btn.classList.toggle('is-active', active);
          btn.setAttribute('aria-selected', String(active));
        });
      };

      featureTabs.forEach(function (btn) {
        btn.addEventListener('click', function () {
          renderFeature(btn.getAttribute('data-feature-tab'));
        });
      });

      assemblySubtabs.forEach(function (btn) {
        btn.addEventListener('click', function () {
          currentAssemblyView = btn.getAttribute('data-assembly-view') || 'panel';
          assemblySubtabs.forEach(function (sub) {
            const active = sub === btn;
            sub.classList.toggle('is-active', active);
            sub.setAttribute('aria-selected', String(active));
          });
          renderFeature('assembly');
        });
      });
    }
  } catch (err) {
    console.error('Feature showcase error:', err);
  }

  // 3. OS Installer Switcher + Clipboard Copy
  try {
    const osTabs = document.querySelectorAll('.os-tab');
    const osShellLabel = document.getElementById('osShellLabel');
    const osPrompt = document.getElementById('osPrompt');
    const osCommand = document.getElementById('osCommand');
    const viewScriptLink = document.getElementById('viewScriptLink');
    const copyBtn = document.getElementById('copyCommandBtn');

    const OS_DATA = {
      windows: {
        shell: 'PowerShell',
        prompt: 'PS>',
        cmd: 'irm "https://badwords.dev/raw/windows" | iex',
        scriptUrl: 'https://github.com/veritus-git/BadWords/blob/main/setupfiles/windows-setup.ps1'
      },
      macos: {
        shell: 'Terminal (zsh / bash)',
        prompt: '$',
        cmd: 'curl -fsSL "https://badwords.dev/raw/mac" | bash',
        scriptUrl: 'https://github.com/veritus-git/BadWords/blob/main/setupfiles/mac-setup.sh'
      },
      linux: {
        shell: 'Terminal (bash)',
        prompt: '$',
        cmd: 'curl -fsSL "https://badwords.dev/raw/linux" | bash',
        scriptUrl: 'https://github.com/veritus-git/BadWords/blob/main/setupfiles/linux-setup.sh'
      }
    };

    const setOS = function (osKey) {
      const data = OS_DATA[osKey];
      if (!data || !osCommand) return;
      if (osShellLabel) osShellLabel.textContent = data.shell;
      if (osPrompt) osPrompt.textContent = data.prompt;
      osCommand.textContent = data.cmd;
      if (viewScriptLink) viewScriptLink.href = data.scriptUrl;
      osTabs.forEach(function (btn) {
        const active = btn.getAttribute('data-os') === osKey;
        btn.classList.toggle('is-active', active);
        btn.setAttribute('aria-selected', String(active));
      });
    };

    if (osTabs.length) {
      osTabs.forEach(function (btn) {
        btn.addEventListener('click', function () {
          setOS(btn.getAttribute('data-os'));
        });
      });

      const defaultOs = document.body.getAttribute('data-default-os');
      if (defaultOs && OS_DATA[defaultOs]) {
        setOS(defaultOs);
      } else {
        const ua = (navigator.userAgent || '').toLowerCase();
        if (ua.indexOf('mac') !== -1) setOS('macos');
        else if (ua.indexOf('linux') !== -1 && ua.indexOf('android') === -1) setOS('linux');
      }
    }

    if (copyBtn && osCommand) {
      let resetTimer = null;
      copyBtn.addEventListener('click', async function () {
        const text = osCommand.textContent.trim();
        try {
          if (navigator.clipboard && navigator.clipboard.writeText) {
            await navigator.clipboard.writeText(text);
          } else {
            const ta = document.createElement('textarea');
            ta.value = text;
            ta.style.position = 'fixed';
            ta.style.opacity = '0';
            document.body.appendChild(ta);
            ta.select();
            document.execCommand('copy');
            document.body.removeChild(ta);
          }
          copyBtn.textContent = 'Copied!';
          copyBtn.classList.add('is-copied');
          if (resetTimer) clearTimeout(resetTimer);
          resetTimer = setTimeout(function () {
            copyBtn.textContent = 'Copy';
            copyBtn.classList.remove('is-copied');
          }, 2000);
        } catch (err) {
          console.error('Copy failed:', err);
        }
      });
    }
  } catch (err) {
    console.error('Installer switcher error:', err);
  }

  // 4. Fullscreen Lightbox Modal
  try {
    const modal = document.getElementById('lightboxModal');
    const modalImg = document.getElementById('lightboxImg');
    const modalCaption = document.getElementById('lightboxCaption');
    const closeBtn = document.getElementById('lightboxCloseBtn');
    let lastTrigger = null;

    if (modal && modalImg && modalCaption) {
      const openModal = function (src, caption, triggerEl) {
        lastTrigger = triggerEl || null;
        modalImg.src = src;
        modalImg.alt = caption || 'BadWords screenshot preview';
        modalCaption.textContent = caption || '';
        modal.classList.add('is-open');
        document.body.style.overflow = 'hidden';
        if (closeBtn) closeBtn.focus();
      };

      const closeModal = function () {
        modal.classList.remove('is-open');
        modalImg.src = '';
        document.body.style.overflow = '';
        if (lastTrigger && typeof lastTrigger.focus === 'function') {
          lastTrigger.focus();
        }
      };

      document.querySelectorAll('.lightbox-trigger').forEach(function (trigger) {
        trigger.addEventListener('click', function () {
          const src = trigger.getAttribute('data-lightbox-src');
          const caption = trigger.getAttribute('data-lightbox-caption') || '';
          if (src) openModal(src, caption, trigger);
        });
      });

      if (closeBtn) closeBtn.addEventListener('click', closeModal);
      modal.addEventListener('click', function (e) {
        if (e.target === modal) closeModal();
      });
      document.addEventListener('keydown', function (e) {
        if (e.key === 'Escape' && modal.classList.contains('is-open')) {
          closeModal();
        }
      });
    }
  } catch (err) {
    console.error('Lightbox error:', err);
  }

  // 5. Docs Search Filter & Active Section Highlighter
  try {
    const searchInput = document.getElementById('docsSearchInput');
    const sections = document.querySelectorAll('.docs-article section');
    const navLinks = document.querySelectorAll('.docs-nav a');

    if (searchInput && sections.length) {
      searchInput.addEventListener('input', function () {
        const q = searchInput.value.trim().toLowerCase();
        sections.forEach(function (sec) {
          const match = !q || sec.textContent.toLowerCase().indexOf(q) !== -1;
          sec.classList.toggle('hidden', !match);
        });
      });
    }

    if (navLinks.length && sections.length && 'IntersectionObserver' in window) {
      const observer = new IntersectionObserver(function (entries) {
        entries.forEach(function (entry) {
          if (entry.isIntersecting) {
            const id = entry.target.getAttribute('id');
            navLinks.forEach(function (link) {
              link.classList.toggle('is-active', link.getAttribute('href') === '#' + id);
            });
          }
        });
      }, { rootMargin: '-20% 0px -70% 0px' });

      sections.forEach(function (sec) { observer.observe(sec); });
    }
  } catch (err) {
    console.error('Docs helper error:', err);
  }
})();
